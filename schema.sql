-- Execute no SQL Editor de um projeto Supabase NOVO.
create extension if not exists pgcrypto;
create table public.profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nome text not null default '',
 role text not null default 'viewer' check (role in ('admin','editor','viewer')),
 ativo boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.empresas (
 id bigint generated by default as identity primary key,
 nome text not null,
 cnpj text not null default '', codigo text not null default '',
 grupo text not null default 'Legacy' check (grupo in ('Legacy','Econtábil','Premium')),
 carteira text not null default '', responsavel text not null default '',
 regime text not null default '', cidade text not null default '',
 status text not null default 'conferencia' check (status in ('ativa','conferencia','programada','saiu')),
 entrada date, "saidaPrev" date, saida date,
 motivo text not null default '', obs text not null default '',
 origem text not null default '', conferencia text not null default '',
 historico jsonb not null default '[]'::jsonb,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index empresas_cnpj_unico on public.empresas (regexp_replace(cnpj,'[^0-9]','','g')) where length(regexp_replace(cnpj,'[^0-9]','','g'))=14;
create table public.movimentacoes (
 id bigint generated always as identity primary key,
 empresa_id bigint references public.empresas(id) on delete set null,
 empresa_nome text not null default '',
 tipo text not null, detalhes jsonb not null default '{}'::jsonb,
 usuario_id uuid not null default auth.uid() references auth.users(id),
 criado_em timestamptz not null default now()
);
create function public.my_role() returns text language sql stable security definer set search_path='' as $$
 select role from public.profiles where user_id=(select auth.uid()) and ativo=true limit 1
$$;
revoke all on function public.my_role() from public;
grant execute on function public.my_role() to authenticated;
alter table public.profiles enable row level security;
alter table public.empresas enable row level security;
alter table public.movimentacoes enable row level security;
create policy profiles_read on public.profiles for select to authenticated using (user_id=(select auth.uid()) or public.my_role()='admin');
create policy profiles_admin_insert on public.profiles for insert to authenticated with check (public.my_role()='admin');
create policy profiles_admin_update on public.profiles for update to authenticated using (public.my_role()='admin') with check (public.my_role()='admin');
create policy empresas_read on public.empresas for select to authenticated using (public.my_role() in ('admin','editor','viewer'));
create policy empresas_insert on public.empresas for insert to authenticated with check (public.my_role() in ('admin','editor'));
create policy empresas_update on public.empresas for update to authenticated using (public.my_role() in ('admin','editor')) with check (public.my_role() in ('admin','editor'));
create policy empresas_delete on public.empresas for delete to authenticated using (public.my_role()='admin');
create policy movimentos_read on public.movimentacoes for select to authenticated using (public.my_role() in ('admin','editor','viewer'));
-- Eventos de auditoria são gerados no servidor, não pelo navegador.
create function public.audit_empresa() returns trigger language plpgsql security definer set search_path='' as $$
declare mudancas jsonb; tipo text;
begin
 if tg_op='INSERT' then
   insert into public.movimentacoes(empresa_id,empresa_nome,tipo,detalhes,usuario_id)
   values(new.id,new.nome,'cadastro',jsonb_build_object('novo',to_jsonb(new)),(select auth.uid()));
   return new;
 elsif tg_op='DELETE' then
   insert into public.movimentacoes(empresa_id,empresa_nome,tipo,detalhes,usuario_id)
   values(null,old.nome,'exclusao',jsonb_build_object('anterior',to_jsonb(old)),(select auth.uid()));
   return old;
 else
   mudancas=jsonb_build_object('anterior',to_jsonb(old),'novo',to_jsonb(new));
   tipo=case when old.grupo is distinct from new.grupo or old.carteira is distinct from new.carteira then 'transferencia'
        when old.status is distinct from new.status or old."saidaPrev" is distinct from new."saidaPrev" or old.saida is distinct from new.saida then 'saida' else 'edicao' end;
   insert into public.movimentacoes(empresa_id,empresa_nome,tipo,detalhes,usuario_id)
   values(new.id,new.nome,tipo,mudancas,(select auth.uid()));
   return new;
 end if;
end $$;
create trigger empresas_audit after insert or update or delete on public.empresas for each row execute function public.audit_empresa();
create function public.set_updated_at() returns trigger language plpgsql set search_path='' as $$ begin new.updated_at=now();return new;end $$;
create trigger empresas_updated before update on public.empresas for each row execute function public.set_updated_at();
